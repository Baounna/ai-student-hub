#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const TARGET_DIRS = [path.join(ROOT, "src/app"), path.join(ROOT, "src/components")];
const EXCLUDED_PATHS = new Set([
  path.join(ROOT, "src/app/[lang]/growth-sprint/page.tsx"),
  path.join(ROOT, "src/app/growth-sprint/page.tsx")
]);
const FILE_PATTERN = /\.(ts|tsx|mdx)$/i;

const RULES = [
  {
    label: "Internal revenue phrasing",
    pattern: /\b(revenue angle|angle revenu|monetization angle)\b/i
  },
  {
    label: "Private operator wording",
    pattern: /\b(internal target|private operator|internal draft generated by blog operator agent)\b/i
  },
  {
    label: "Automation disclosure wording",
    pattern: /\b(without manual intervention|sans intervention manuelle|no manual intervention)\b/i
  },
  {
    label: "Private KPI copy",
    pattern: /\b(kpi checkpoints|kpi a suivre|ctr, opt-ins)\b/i
  }
];

async function walk(dir) {
  const output = [];
  let entries = [];
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return output;
  }

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (EXCLUDED_PATHS.has(fullPath)) continue;
    if (entry.isDirectory()) {
      output.push(...(await walk(fullPath)));
      continue;
    }
    if (entry.isFile() && FILE_PATTERN.test(entry.name)) {
      output.push(fullPath);
    }
  }

  return output;
}

function getLineNumber(content, index) {
  const chunk = content.slice(0, index);
  return chunk.split("\n").length;
}

async function run() {
  const files = (
    await Promise.all(TARGET_DIRS.map((dir) => walk(dir)))
  ).flat();

  const findings = [];

  for (const file of files) {
    const content = await fs.readFile(file, "utf8");

    for (const rule of RULES) {
      const match = rule.pattern.exec(content);
      if (!match || match.index < 0) continue;

      findings.push({
        file: path.relative(ROOT, file),
        rule: rule.label,
        line: getLineNumber(content, match.index),
        snippet: match[0]
      });
    }
  }

  console.log("Public content privacy check");
  console.log("----------------------------");

  if (!findings.length) {
    console.log("No private/internal wording found in public-facing copy.");
    return;
  }

  for (const finding of findings) {
    console.error(`- ${finding.file}:${finding.line} | ${finding.rule} | "${finding.snippet}"`);
  }

  process.exitCode = 1;
}

run().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
