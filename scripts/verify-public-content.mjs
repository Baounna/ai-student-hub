#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const TARGET_DIRS = [path.join(ROOT, "src/app"), path.join(ROOT, "src/components")];
const EXCLUDED_PATHS = new Set([
  path.join(ROOT, "src/app/[lang]/growth-sprint/page.tsx"),
  path.join(ROOT, "src/app/growth-sprint/page.tsx")
]);
const FILE_PATTERN = /\.(ts|tsx|mdx)$/i;

const RULES = [
  {
    label: "Internal revenue phrasing",
    pattern: /\b(revenue angle|angle revenu|monetization angle)\b/i
  },
  {
    label: "Private operator wording",
    pattern: /\b(internal target|private operator|internal draft generated by blog operator agent)\b/i
  },
  {
    label: "Automation disclosure wording",
    pattern: /\b(without manual intervention|sans intervention manuelle|no manual intervention)\b/i
  },
  {
    label: "Private KPI copy",
    pattern: /\b(kpi checkpoints|kpi a suivre|ctr, opt-ins)\b/i
  }
];

async function walk(dir) {
  const output = [];
  let entries = [];
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return output;
  }

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (EXCLUDED_PATHS.has(fullPath)) continue;
    if (entry.isDirectory()) {
      output.push(...(await walk(fullPath)));
      continue;
    }
    if (entry.isFile() && FILE_PATTERN.test(entry.name)) {
      output.push(fullPath);
    }
  }

  return output;
}

function getLineNumber(content, index) {
  const chunk = content.slice(0, index);
  return chunk.split("\n").length;
}

/**
 * How few files would mean the scan has stopped working.
 *
 * src/app and src/components hold well over a hundred files between them. The
 * number is a floor rather than the real count so that deleting a page does not
 * fail this check; it is here to catch a walk that returned almost nothing.
 */
const MINIMUM_FILES = 60;

async function run() {
  const files = (
    await Promise.all(TARGET_DIRS.map((dir) => walk(dir)))
  ).flat();

  /*
   * walk() swallows a failed readdir and returns an empty list, and nothing
   * after it asked how many files there were. Rename src/app, move a directory,
   * or run this from the wrong working directory and it printed "No
   * private/internal wording found in public-facing copy." over nothing at all,
   * and exited 0.
   *
   * That is the failure this repository keeps meeting: a report that says
   * success on a path it never exercised. The clock sweep did it with a vitest
   * flag that no longer existed, and the stage check's workflow did it by
   * grepping for prose the script does not print. A privacy scan is a poor
   * place for it -- its whole job is to be the thing that notices.
   */
  if (files.length < MINIMUM_FILES) {
    console.error("Public content privacy check");
    console.error("----------------------------");
    console.error(
      `Only ${files.length} file(s) were scanned, and there should be at least ${MINIMUM_FILES}.`
    );
    console.error(
      "Nothing was verified. Check that this ran from the repository root and that",
      `\n${TARGET_DIRS.map((dir) => path.relative(ROOT, dir)).join(" and ")} still exist.`
    );
    process.exitCode = 1;
    return;
  }

  const findings = [];

  for (const file of files) {
    const content = await fs.readFile(file, "utf8");

    for (const rule of RULES) {
      const match = rule.pattern.exec(content);
      if (!match || match.index < 0) continue;

      findings.push({
        file: path.relative(ROOT, file),
        rule: rule.label,
        line: getLineNumber(content, match.index),
        snippet: match[0]
      });
    }
  }

  console.log("Public content privacy check");
  console.log("----------------------------");

  if (!findings.length) {
    console.log("No private/internal wording found in public-facing copy.");
    return;
  }

  for (const finding of findings) {
    console.error(`- ${finding.file}:${finding.line} | ${finding.rule} | "${finding.snippet}"`);
  }

  process.exitCode = 1;
}

run().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
