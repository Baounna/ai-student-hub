#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const QUEUE_FILE = path.join(ROOT, "docs/agent/next-actions.json");
const STATE_FILE = path.join(ROOT, "docs/agent/issues-state.json");
const REPORT_FILE = path.join(ROOT, "docs/agent/issues-report.md");

const PRIORITY_RANK = {
  P1: 1,
  P2: 2,
  P3: 3
};

function toInteger(value, fallback) {
  const parsed = Number.parseInt(String(value || ""), 10);
  return Number.isFinite(parsed) ? parsed : fallback;
}

function toBoolean(value, fallback) {
  if (value == null || value === "") return fallback;
  const normalized = String(value).trim().toLowerCase();
  if (["1", "true", "yes", "on", "enabled", "enable"].includes(normalized)) return true;
  if (["0", "false", "no", "off", "disabled", "disable"].includes(normalized)) return false;
  return fallback;
}

function shortHash(input) {
  return crypto.createHash("sha256").update(input).digest("hex").slice(0, 16);
}

function normalizePriority(value) {
  const normalized = String(value || "").trim().toUpperCase();
  return normalized === "P1" || normalized === "P2" || normalized === "P3" ? normalized : "P3";
}

function buildActionHash(item) {
  return shortHash(`${normalizePriority(item.priority)}|${String(item.action || "").trim()}|${String(item.why || "").trim()}`);
}

function truncate(value, limit) {
  const normalized = String(value || "").replace(/\s+/g, " ").trim();
  if (normalized.length <= limit) return normalized;
  return `${normalized.slice(0, Math.max(0, limit - 1)).trimEnd()}…`;
}

function buildIssueTitle(item) {
  const priority = normalizePriority(item.priority);
  return `[Operator ${priority}] ${truncate(item.action || "Operator task", 86)}`;
}

async function safeReadJson(file, fallback) {
  try {
    const raw = await fs.readFile(file, "utf8");
    return JSON.parse(raw);
  } catch {
    return fallback;
  }
}

async function ensureDir(filePath) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
}

function prioritySort(a, b) {
  const rankA = PRIORITY_RANK[normalizePriority(a.priority)] || 99;
  const rankB = PRIORITY_RANK[normalizePriority(b.priority)] || 99;
  if (rankA !== rankB) return rankA - rankB;
  return String(a.action || "").localeCompare(String(b.action || ""));
}

function buildIssueBody({ generatedAt, item }) {
  const priority = normalizePriority(item.priority);
  return [
    "## Operator Task",
    "",
    `- Priority: ${priority}`,
    `- Action: ${String(item.action || "").trim()}`,
    `- Why: ${String(item.why || "").trim()}`,
    "",
    "## Source",
    "",
    "- Generated by: Blog Operator Agent",
    "- Source file: `docs/agent/next-actions.json`",
    `- Queue timestamp: ${generatedAt}`,
    "",
    "## Acceptance",
    "",
    "- [ ] Implement this action in code/content/config",
    "- [ ] Run `npm run lint`",
    "- [ ] Run `npm run build`",
    "- [ ] Update docs if behavior changed",
    "",
    `Tracking hash: \`${buildActionHash(item)}\``,
    ""
  ].join("\n");
}

async function githubRequest({ repository, token, method, apiPath, body }) {
  const url = `https://api.github.com/repos/${repository}${apiPath}`;
  const response = await fetch(url, {
    method,
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${token}`,
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json"
    },
    body: body ? JSON.stringify(body) : undefined
  });

  if (!response.ok) {
    const raw = await response.text();
    throw new Error(`${method} ${apiPath} failed (${response.status}): ${truncate(raw, 360)}`);
  }

  return response.json();
}

function buildReport({
  generatedAt,
  mode,
  repository,
  queueGeneratedAt,
  maxPerRun,
  created,
  existing,
  dryRun,
  errors,
  tracked
}) {
  const lines = [];
  lines.push("# AI Student Hub Operator Issue Sync");
  lines.push("");
  lines.push(`Generated: ${generatedAt}`);
  lines.push(`Mode: ${mode}`);
  lines.push(`Repository: ${repository || "(not set)"}`);
  lines.push(`Queue timestamp: ${queueGeneratedAt || "unknown"}`);
  lines.push(`Max issues per run: ${maxPerRun}`);
  lines.push("");
  lines.push("## Run Summary");
  lines.push(`- Created: ${created.length}`);
  lines.push(`- Already open/tracked: ${existing.length}`);
  lines.push(`- Dry-run candidates: ${dryRun.length}`);
  lines.push(`- Errors: ${errors.length}`);
  lines.push("");

  if (created.length) {
    lines.push("## Created");
    created.forEach((item) => lines.push(`- #${item.issueNumber} ${item.title}`));
    lines.push("");
  }

  if (existing.length) {
    lines.push("## Existing");
    existing.forEach((item) => {
      const issueLabel = item.issueNumber ? `#${item.issueNumber}` : "(tracked)";
      lines.push(`- ${issueLabel} ${item.title}`);
    });
    lines.push("");
  }

  if (dryRun.length) {
    lines.push("## Dry-run");
    dryRun.forEach((item) => lines.push(`- ${item.title}`));
    lines.push("");
  }

  if (errors.length) {
    lines.push("## Errors");
    errors.forEach((error) => lines.push(`- ${error}`));
    lines.push("");
  }

  lines.push("## Tracked Actions");
  tracked
    .slice()
    .sort((a, b) => prioritySort(a, b))
    .forEach((item) => {
      lines.push(`- [${normalizePriority(item.priority)}] ${item.action}`);
      if (item.issueNumber) {
        lines.push(`  - Issue: #${item.issueNumber}`);
      }
      lines.push(`  - Status: ${item.status}`);
      lines.push(`  - Last seen: ${item.lastSeenAt}`);
    });
  lines.push("");

  return `${lines.join("\n")}\n`;
}

async function run() {
  const generatedAt = new Date().toISOString();
  const enabled = toBoolean(process.env.AGENT_ISSUES_ENABLED, true);
  const maxPerRun = Math.max(0, Math.min(toInteger(process.env.AGENT_ISSUES_MAX_PER_RUN, 3), 20));
  const token = (process.env.GITHUB_TOKEN || process.env.GH_TOKEN || "").trim();
  const repository = (process.env.GITHUB_REPOSITORY || "").trim();

  const queue = await safeReadJson(QUEUE_FILE, { actions: [], generatedAt: "" });
  const queueGeneratedAt = String(queue.generatedAt || "").trim();
  const queueActions = Array.isArray(queue.actions) ? queue.actions : [];

  const state = await safeReadJson(STATE_FILE, {
    generatedAt: "",
    repository,
    mode: "init",
    items: []
  });

  const existingStateItems = Array.isArray(state.items) ? state.items : [];
  const stateByHash = new Map(existingStateItems.map((item) => [item.hash, item]));

  const mode = !enabled ? "disabled" : token && repository ? "enabled" : "dry-run";
  const selectedActions = queueActions.slice().sort(prioritySort).slice(0, maxPerRun);

  let openIssues = [];
  if (mode === "enabled") {
    const open = await githubRequest({
      repository,
      token,
      method: "GET",
      apiPath: "/issues?state=open&per_page=100"
    });
    openIssues = Array.isArray(open) ? open.filter((item) => !item.pull_request) : [];
  }

  const openByTitle = new Map(openIssues.map((issue) => [issue.title, issue]));

  const created = [];
  const existing = [];
  const dryRun = [];
  const errors = [];
  const touchedHashes = new Set();

  for (const item of selectedActions) {
    const priority = normalizePriority(item.priority);
    const actionText = String(item.action || "").trim();
    const whyText = String(item.why || "").trim();
    const hash = buildActionHash(item);
    const title = buildIssueTitle(item);

    if (!actionText) continue;

    const previous = stateByHash.get(hash);
    const existingIssue = openByTitle.get(title);

    const nextStateItem = {
      hash,
      priority,
      action: actionText,
      why: whyText,
      title,
      issueNumber: previous?.issueNumber,
      issueUrl: previous?.issueUrl,
      status: "tracked",
      createdAt: previous?.createdAt || generatedAt,
      lastSeenAt: generatedAt,
      inQueue: true
    };

    touchedHashes.add(hash);

    if (existingIssue) {
      nextStateItem.issueNumber = existingIssue.number;
      nextStateItem.issueUrl = existingIssue.html_url;
      nextStateItem.status = "already_open";
      existing.push(nextStateItem);
      stateByHash.set(hash, nextStateItem);
      continue;
    }

    if (previous?.issueNumber) {
      nextStateItem.status = "already_tracked";
      existing.push(nextStateItem);
      stateByHash.set(hash, nextStateItem);
      continue;
    }

    if (mode !== "enabled") {
      nextStateItem.status = mode;
      dryRun.push(nextStateItem);
      stateByHash.set(hash, nextStateItem);
      continue;
    }

    try {
      const createdIssue = await githubRequest({
        repository,
        token,
        method: "POST",
        apiPath: "/issues",
        body: {
          title,
          body: buildIssueBody({ generatedAt: queueGeneratedAt || generatedAt, item })
        }
      });

      nextStateItem.issueNumber = createdIssue.number;
      nextStateItem.issueUrl = createdIssue.html_url;
      nextStateItem.status = "created";
      created.push(nextStateItem);
      stateByHash.set(hash, nextStateItem);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      nextStateItem.status = "error";
      errors.push(`${title}: ${message}`);
      stateByHash.set(hash, nextStateItem);
    }
  }

  for (const [hash, item] of stateByHash.entries()) {
    if (touchedHashes.has(hash)) continue;
    stateByHash.set(hash, {
      ...item,
      inQueue: false,
      status: item.status || "historical"
    });
  }

  const tracked = Array.from(stateByHash.values()).sort((a, b) => prioritySort(a, b));

  const nextState = {
    generatedAt,
    repository,
    mode,
    queueGeneratedAt,
    maxPerRun,
    summary: {
      created: created.length,
      existing: existing.length,
      dryRun: dryRun.length,
      errors: errors.length,
      tracked: tracked.length
    },
    items: tracked
  };

  const report = buildReport({
    generatedAt,
    mode,
    repository,
    queueGeneratedAt,
    maxPerRun,
    created,
    existing,
    dryRun,
    errors,
    tracked
  });

  await ensureDir(STATE_FILE);
  await fs.writeFile(STATE_FILE, `${JSON.stringify(nextState, null, 2)}\n`, "utf8");
  await fs.writeFile(REPORT_FILE, report, "utf8");

  console.log("Operator Issue Sync");
  console.log("--------------------");
  console.log(`Mode: ${mode}`);
  console.log(`Created: ${created.length}`);
  console.log(`Existing: ${existing.length}`);
  console.log(`Dry-run: ${dryRun.length}`);
  console.log(`Errors: ${errors.length}`);
  console.log(`State: ${path.relative(ROOT, STATE_FILE)}`);
  console.log(`Report: ${path.relative(ROOT, REPORT_FILE)}`);

  if (errors.length && mode === "enabled") {
    process.exitCode = 1;
  }
}

run().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
